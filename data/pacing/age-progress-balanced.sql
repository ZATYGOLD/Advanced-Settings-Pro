-- Age Progression: Balanced. Milestone and future tech/civic points per age;
-- only the current age's rows exist, so each age takes its own figures.
UPDATE AgeProgressionEvents
SET Points = CASE AgeProgressionType
        WHEN 'AGE_PROGRESSION_ANTIQUITY_AGE_TIMER' THEN CASE AgeProgressionEventType
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_1' THEN 4
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_2' THEN 7
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_3' THEN 11
            WHEN 'AGE_PROGRESSION_FUTURE_CIVIC' THEN 8
            WHEN 'AGE_PROGRESSION_FUTURE_TECH' THEN 8
            ELSE Points END
        WHEN 'AGE_PROGRESSION_EXPLORATION_AGE_TIMER' THEN CASE AgeProgressionEventType
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_1' THEN 4
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_2' THEN 8
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_3' THEN 12
            WHEN 'AGE_PROGRESSION_FUTURE_CIVIC' THEN 8
            WHEN 'AGE_PROGRESSION_FUTURE_TECH' THEN 8
            ELSE Points END
        WHEN 'AGE_PROGRESSION_MODERN_AGE_TIMER' THEN CASE AgeProgressionEventType
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_1' THEN 4
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_2' THEN 8
            WHEN 'AGE_PROGRESSION_PLAYER_MILESTONE_3' THEN 0
            WHEN 'AGE_PROGRESSION_FUTURE_CIVIC' THEN 7
            WHEN 'AGE_PROGRESSION_FUTURE_TECH' THEN 7
            ELSE Points END
        ELSE Points
    END;
